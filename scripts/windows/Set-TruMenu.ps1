    Installs or removes TruMenu.asi (in-game debug menu, Dear ImGui, L3 + R3) next to tru.exe.

.DESCRIPTION
    -Install copies <workspace>\work\asi\TruMenu.asi (built by Build-TruAsi.ps1) and its sample .ini into the
             game folder; the Ultimate ASI Loader the game ships as binkw32.dll loads every *.asi there.
    -Remove  deletes them again - only if they are ours (same SHA-256 as the built file / the sample .ini, or one of
             our earlier released builds listed in $earlierBuilds); a foreign file of the same name is never
             overwritten or removed. TruMenu.log is left in place.
    -Install over an earlier build of ours replaces it (update); an .ini the owner edited is not ours and is kept
             (the plugin's built-in defaults cover options it lacks).
    0.8: also the regression lists tests\regress\dlc1.txt / dlc2.txt -> TruMenu.regress_dlc1.txt / _dlc2.txt next to
             the .asi (taken from the build folder when it holds TruMenu.regress_*.txt, else from tests\regress). A
             list is ours when its first line starts with "# TruMenu regression list"; a foreign file of that name is
             kept. TruMenu.regress_results.txt (the owner's results) is never touched.
    0.9: also TruMenu.media.txt (generated by tools/music_list.py --menu-out <build folder>, only from the build
             folder; ours = first line "# TruMenu media list"). The Saves page folder TruMenu.saves is never touched.
             0.22.18: without a list in the build folder the last generated work\media\menu\TruMenu.media.txt is
             installed (warning with its date).
    0.10: also the radial menu file TruMenu.radial.txt next to tru.exe (from the build folder, else
             src\asi\TruMenu\TruMenu.radial.txt; ours = first line starts with "# TruMenu radial menu"; a file the
             owner edited keeps that line and is replaced by -Install - copy it away first if you changed it).
    0.10.1: also the tour file TruMenu.tour.txt (radial level Tests / Rundgang, written by tools/tour_from_rundgang.py)
             the same way (ours = first line starts with "# TruMenu tour").
    0.21.5: also the switches file TruMenu.switches.txt (bar page / menu section Fixes: the plugin INI switches) the
             same way (ours = first line starts with "# TruMenu switches"); -Remove deletes only one of ours.
    0.21.7: also the shader label data TruMenu.shaderlabel.txt (tools/shader_labels.py build; generated locally, never
             in the repository) from the build folder when present, as the media list (ours = first line starts with
             "# shaderlabel v1"); missing = shader.labels stays empty.
    0.21.9: -ShaderLabelFile <path> installs that shader label data file (e.g. a variant of
             work\shader17c_0811\trumenu\<variant>\TruMenu.shaderlabel.txt) as TruMenu.shaderlabel.txt instead of the one
             in the build folder; it must start with "# shaderlabel v1" (checked before anything is copied). Without the
             parameter nothing changes.
    0.11: the flow file TruMenu.flow.txt next to tru.exe belongs to a test profile (its "flowFile", installed by
             Invoke-TruTestRun.ps1 after this script): -Install and -Remove both delete one of ours (first line starts
             with "# TruMenu flow") so no flow of an earlier run is left; a foreign file of that name is kept.
    0.21: the owner's own arachnophobia picture TruMenu.arachno*.png next to tru.exe is never copied, overwritten or
             removed (-Install / -Remove); one in the build folder is not installed either (Assert-NotOwnerImage).
    The game must not be running. Every run writes <workspace>\logs\Set-TruMenu_<time>.log. -Verbose shows the
    steps, -Debug the hashes, -Trace adds a PowerShell line trace.

.PARAMETER GamePath
    Game folder; default: found through the Steam libraries.

.PARAMETER ShaderLabelFile
    0.21.9, -Install only: a shader label data file to install as TruMenu.shaderlabel.txt instead of the build folder's
    (first line "# shaderlabel v1"). Default: the build folder's file as before.

.EXAMPLE
    .\Set-TruMenu.ps1 -Install -Verbose
    .\Set-TruMenu.ps1 -Install -SourceDir .\work\asi\menu0222 -ShaderLabelFile .\work\shader17c_0811\trumenu\stack_n5mats_n6_17c\TruMenu.shaderlabel.txt
