# 0.21: the owner's own arachnophobia picture (TruMenu.arachno.png, also TruMenu.arachno.<kind>.png) next to tru.exe is
# private: this script never copies, overwrites or removes it (not even one found in the build folder) - the plugin
# falls back to its built-in picture without it
$ownerImagePattern = 'TruMenu.arachno*.png'
function Assert-NotOwnerImage {
    param([string]$Path)
    if ((Split-Path -Leaf $Path) -like $ownerImagePattern) { throw "refused: $Path is the owner's own picture ($ownerImagePattern) - never copied or removed." }
}
# 0.10 radial menu file and 0.10.1 tour file (next to tru.exe; the default comes from the build folder or src\asi\TruMenu)
$radialFiles = @(
    @{ File = 'TruMenu.radial.txt'; Marker = '# TruMenu radial menu'; Missing = 'radial menu file not installed (the ring stays empty)' },
    @{ File = 'TruMenu.tour.txt'; Marker = '# TruMenu tour'; Missing = 'tour file not installed (radial level Tests / Rundgang stays empty)' },
    @{ File = 'TruMenu.switches.txt'; Marker = '# TruMenu switches'; Missing = 'switches file not installed (page Fixes stays empty)' }   # 0.21.5
)
# 0.9 media list (generated by tools/music_list.py --menu-out <build folder>; never in the repository)
$mediaList = 'TruMenu.media.txt'
$mediaMarker = '# TruMenu media list'
# 0.21.7 shader label data (tools/shader_labels.py build; never in the repository) - [Shader] File of TruMenu.ini
$shaderList = 'TruMenu.shaderlabel.txt'
$shaderMarker = '# shaderlabel v1'
# 0.8 regression lists: target name -> source name in tests\regress (or the same target name in the build folder)
$regressLists = [ordered]@{ 'TruMenu.regress_dlc1.txt' = 'dlc1.txt'; 'TruMenu.regress_dlc2.txt' = 'dlc2.txt' }
$regressMarker = '# TruMenu regression list'
$logDir  = $paths.Logs
New-Item -ItemType Directory -Force -Path $logDir | Out-Null
$logFile = Join-Path $logDir ('Set-TruMenu_{0}_{1}.log' -f (Get-Date -Format 'yyyyMMdd_HHmmss'), $PSCmdlet.ParameterSetName)
Set-TruLogFile -Path $logFile

function Get-Sha256 {
    param([string]$Path)
    (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash.ToLower()
}

if ($Trace) { Set-PSDebug -Trace 1 }
try {
    Write-Log "Set-TruMenu mode=$($PSCmdlet.ParameterSetName) log=$logFile" -Level VERBOSE
    if (Get-Process -Name 'tru' -ErrorAction SilentlyContinue) { throw 'Tomb Raider: Underworld is running. Please close it first.' }
    if (!$GamePath) { $GamePath = Find-TruGamePath }
    if (!$GamePath -or !(Test-Path -LiteralPath (Join-Path $GamePath 'tru.exe'))) { throw "Game folder not found (-GamePath): $GamePath" }
    Write-Log "Game folder: $GamePath" -Level VERBOSE
    # 0.21.9 -ShaderLabelFile: checked before anything is copied (a wrong file stops the whole install)
    if ($ShaderLabelFile) {
        if (!(Test-Path -LiteralPath $ShaderLabelFile -PathType Leaf)) { throw "-ShaderLabelFile not found: $ShaderLabelFile" }
        $firstLabel = Get-Content -LiteralPath $ShaderLabelFile -TotalCount 1 -ErrorAction SilentlyContinue
        if (!($firstLabel -and ([string]$firstLabel).StartsWith($shaderMarker))) {
            throw "-ShaderLabelFile $ShaderLabelFile does not start with '$shaderMarker' (tools/shader_labels.py build output) - nothing installed."
        }
        Write-Log "-ShaderLabelFile $ShaderLabelFile sha256 $(Get-Sha256 $ShaderLabelFile) (installed as $shaderList)" -Level VERBOSE
    }

    foreach ($name in $names) {
        $source = Join-Path $built $name
        $target = Join-Path $GamePath $name
        if (!(Test-Path -LiteralPath $source)) { throw "$source not found (run Build-TruAsi.ps1 first)." }
        $sourceHash = Get-Sha256 $source
        Write-Log "$name built sha256 $sourceHash" -Level DEBUG
        $targetHash = if (Test-Path -LiteralPath $target) { Get-Sha256 $target } else { $null }
        if ($targetHash) { Write-Log "$name installed sha256 $targetHash" -Level DEBUG }
        $isEarlier = $targetHash -and ($earlierBuilds[$name] -contains $targetHash)
        if ($Install) {
            if ($targetHash -eq $sourceHash) { Write-Log "$name already installed."; continue }
            if ($targetHash -and !$isEarlier) {
                if ($name -like '*.ini') { Write-Log "$target was edited (not a build of ours) - kept." -Level WARN; continue }
                throw "$target exists and is not a build of ours - left untouched."
            }
            Assert-NotOwnerImage $target; Copy-Item -LiteralPath $source -Destination $target -Force
            if ($isEarlier) { Write-Log "$name updated in $GamePath (earlier build replaced)." }
            else { Write-Log "$name copied to $target." }
        }
        else {
            if (!$targetHash) { Write-Log "$name not in the game folder." -Level VERBOSE; continue }
            if ($targetHash -ne $sourceHash -and !$isEarlier) { Write-Log "$target is not a build of ours - left untouched." -Level WARN; continue }
            Assert-NotOwnerImage $target; Remove-Item -LiteralPath $target
            Write-Log "$name removed from $GamePath."
        }
    }

    # 0.8 regression lists (plain text, no game data); ours = first line starts with $regressMarker
    foreach ($entry in $regressLists.GetEnumerator()) {
        $target = Join-Path $GamePath $entry.Key
        $isOurs = $false
        if (Test-Path -LiteralPath $target) {
            $first = Get-Content -LiteralPath $target -TotalCount 1 -ErrorAction SilentlyContinue
            $isOurs = [bool]($first -and ([string]$first).StartsWith($regressMarker))
        }
        if ($Install) {
            $source = Join-Path $built $entry.Key
            if (!(Test-Path -LiteralPath $source)) { $source = Join-Path $repo ('tests\regress\' + $entry.Value) }
            if (!(Test-Path -LiteralPath $source)) { Write-Log "$source not found - regression list $($entry.Key) not installed." -Level WARN; continue }
            Write-Log "$($entry.Key) source $source sha256 $(Get-Sha256 $source)" -Level DEBUG
            if ((Test-Path -LiteralPath $target) -and !$isOurs) { Write-Log "$target is not a list of ours - left untouched." -Level WARN; continue }
            if ((Test-Path -LiteralPath $target) -and ((Get-Sha256 $target) -eq (Get-Sha256 $source))) { Write-Log "$($entry.Key) already installed."; continue }
            Assert-NotOwnerImage $target; Copy-Item -LiteralPath $source -Destination $target -Force
            Write-Log "$($entry.Key) copied to $target."
        }
        else {
            if (!(Test-Path -LiteralPath $target)) { Write-Log "$($entry.Key) not in the game folder." -Level VERBOSE; continue }
            if (!$isOurs) { Write-Log "$target is not a list of ours - left untouched." -Level WARN; continue }
            Assert-NotOwnerImage $target; Remove-Item -LiteralPath $target
            Write-Log "$($entry.Key) removed from $GamePath."
        }
    }

    # 0.9 media list (track / video names with source and unused? flag); ours = first line starts with $mediaMarker.
    # The Saves page's TruMenu.saves folder (the owner's save backups) is never touched.
    $target = Join-Path $GamePath $mediaList
    $isOurs = $false
    if (Test-Path -LiteralPath $target) {
        $first = Get-Content -LiteralPath $target -TotalCount 1 -ErrorAction SilentlyContinue
        $isOurs = [bool]($first -and ([string]$first).StartsWith($mediaMarker))
    }
    if ($Install) {
        $source = Join-Path $built $mediaList
        if (!(Test-Path -LiteralPath $source)) {
            # 0.22.18: the build makes no list - fall back to the last generated one (tools/music_list.py --menu-out
            # work\media\menu; never in the repository) when it is ours
            $fallback = Join-Path $repo "work\media\menu\$mediaList"
            if (Test-Path -LiteralPath $fallback) {
                $fbFirst = Get-Content -LiteralPath $fallback -TotalCount 1 -ErrorAction SilentlyContinue
                if ($fbFirst -and ([string]$fbFirst).StartsWith($mediaMarker)) {
                    Write-Log "$source not found - using the last generated list $fallback (written $((Get-Item -LiteralPath $fallback).LastWriteTime.ToString('yyyy-MM-dd HH:mm:ss')))." -Level WARN
                    $source = $fallback
                }
            }
        }
        if (!(Test-Path -LiteralPath $source)) {
            Write-Log "$source not found - media list not installed (run tools/music_list.py --menu-out <build folder>); music items stay off." -Level WARN
        }
        elseif ((Test-Path -LiteralPath $target) -and !$isOurs) { Write-Log "$target is not a list of ours - left untouched." -Level WARN }
        elseif ((Test-Path -LiteralPath $target) -and ((Get-Sha256 $target) -eq (Get-Sha256 $source))) { Write-Log "$mediaList already installed." }
        else {
            Assert-NotOwnerImage $target; Copy-Item -LiteralPath $source -Destination $target -Force
            Write-Log "$mediaList copied to $target."
        }
    }
    elseif (Test-Path -LiteralPath $target) {
        if (!$isOurs) { Write-Log "$target is not a list of ours - left untouched." -Level WARN }
        else {
            Assert-NotOwnerImage $target; Remove-Item -LiteralPath $target
            Write-Log "$mediaList removed from $GamePath."
        }
    }

    # 0.21.7 shader label data (written by tools/shader_labels.py build; game ids / status / box centres, generated
    # locally, never in the repository): from the build folder when present; ours = first line starts with $shaderMarker
    $target = Join-Path $GamePath $shaderList
    $isOurs = $false
    if (Test-Path -LiteralPath $target) {
        $first = Get-Content -LiteralPath $target -TotalCount 1 -ErrorAction SilentlyContinue
        $isOurs = [bool]($first -and ([string]$first).StartsWith($shaderMarker))
    }
    if ($Install) {
        $source = if ($ShaderLabelFile) { $ShaderLabelFile } else { Join-Path $built $shaderList }   # 0.21.9
        Write-Log "$shaderList source $source" -Level DEBUG
        if (!(Test-Path -LiteralPath $source)) {
            Write-Log "$source not found - shader label data not installed (tools/shader_labels.py build, then OUT\shaderlabel.txt into the build folder as $shaderList); shader.labels stays empty." -Level WARN
        }
        elseif ((Test-Path -LiteralPath $target) -and !$isOurs) { Write-Log "$target is not a file of ours - left untouched." -Level WARN }
        elseif ((Test-Path -LiteralPath $target) -and ((Get-Sha256 $target) -eq (Get-Sha256 $source))) { Write-Log "$shaderList already installed." }
        else {
            Assert-NotOwnerImage $target; Copy-Item -LiteralPath $source -Destination $target -Force
            Write-Log "$shaderList copied to $target."
        }
    }
    elseif (Test-Path -LiteralPath $target) {
        if (!$isOurs) { Write-Log "$target is not a file of ours - left untouched." -Level WARN }
        else {
            Assert-NotOwnerImage $target; Remove-Item -LiteralPath $target
            Write-Log "$shaderList removed from $GamePath."
        }
    }

    # 0.10 radial menu file, 0.10.1 tour file; ours = first line starts with the marker
    foreach ($spec in $radialFiles) {
        $radialFile = $spec.File
        $target = Join-Path $GamePath $radialFile
        $isOurs = $false
        if (Test-Path -LiteralPath $target) {
            $first = Get-Content -LiteralPath $target -TotalCount 1 -ErrorAction SilentlyContinue
            $isOurs = [bool]($first -and ([string]$first).StartsWith($spec.Marker))
        }
        if ($Install) {
            $source = Join-Path $built $radialFile
            if (!(Test-Path -LiteralPath $source)) { $source = Join-Path $repo ('src\asi\TruMenu\' + $radialFile) }
            if (!(Test-Path -LiteralPath $source)) { Write-Log "$source not found - $($spec.Missing)." -Level WARN }
            else {
                Write-Log "$radialFile source $source sha256 $(Get-Sha256 $source)" -Level DEBUG
                if ((Test-Path -LiteralPath $target) -and !$isOurs) { Write-Log "$target is not a file of ours - left untouched." -Level WARN }
                elseif ((Test-Path -LiteralPath $target) -and ((Get-Sha256 $target) -eq (Get-Sha256 $source))) { Write-Log "$radialFile already installed." }
                else {
                    Assert-NotOwnerImage $target; Copy-Item -LiteralPath $source -Destination $target -Force
                    Write-Log "$radialFile copied to $target."
                }
            }
        }
        elseif (Test-Path -LiteralPath $target) {
            if (!$isOurs) { Write-Log "$target is not a file of ours - left untouched." -Level WARN }
            else {
                Assert-NotOwnerImage $target; Remove-Item -LiteralPath $target
                Write-Log "$radialFile removed from $GamePath."
            }
        }
    }

    # 0.11 flow file of a test profile (Invoke-TruTestRun.ps1 installs the profile's flowFile after this script): one of
    # ours goes on -Install and -Remove, a foreign one is kept
    $flowTarget = Join-Path $GamePath 'TruMenu.flow.txt'
    if (Test-Path -LiteralPath $flowTarget) {
        $first = Get-Content -LiteralPath $flowTarget -TotalCount 1 -Encoding UTF8 -ErrorAction SilentlyContinue
        if ($first -and ([string]$first).TrimStart([char]0xFEFF).StartsWith('# TruMenu flow')) {
            Write-Log "TruMenu.flow.txt sha256 $(Get-Sha256 $flowTarget)" -Level DEBUG
            Assert-NotOwnerImage $flowTarget; Remove-Item -LiteralPath $flowTarget
            Write-Log "TruMenu.flow.txt (a flow of an earlier run) removed from $GamePath."
        }
        else { Write-Log "$flowTarget is not a flow file of ours - left untouched." -Level WARN }
    }

    # 0.21 the owner's picture: only named in the log, never copied / removed
    foreach ($own in @(Get-ChildItem -LiteralPath $GamePath -Filter $ownerImagePattern -File -ErrorAction SilentlyContinue)) {
        Write-Log "$($own.Name) next to tru.exe: the owner's own arachnophobia picture - kept, never touched." -Level VERBOSE
    }
    foreach ($own in @(Get-ChildItem -LiteralPath $built -Filter $ownerImagePattern -File -ErrorAction SilentlyContinue)) {
        Write-Log "$($own.FullName): an owner picture in the build folder is never installed - copy it by hand." -Level WARN
    }
}
catch {
    Write-Log "FAILED: $($_.Exception.Message)" -Level ERROR
    Write-Log ($_.ScriptStackTrace) -Level DEBUG
    throw
}
finally {
    if ($Trace) { Set-PSDebug -Off }
    Write-Host "Log: $logFile"
}
