"""Print the C table of playable units for TruMenu's level select (read-only; TruMenu 0.2, 2026-10-31).

Source: the PC unit list the game itself loads, tr8/pc-w/unitlist.txt ("N\\r\\n" then "path\\r\\n" * N, format in
tools/objlists.py) - the merged list (PC base + DLC) written by tools/objlists.py, identical to the installed
mods/tr8/pc-w/unitlist.txt. Groups:
  base game : levels\\l*\\...   grouped by the unit name prefix l1_ .. l7_ (l7_* units live in the folder levels\\l5)
  DLC 1     : dlc\\dlc_level1\\...
  DLC 2     : dlc\\dlc_level2\\...
  DLC other : dlc\\dlc_level3..6\\... (start units only)
Not offered (not playable levels): container\\*, dlc\\container\\*, dlc\\dlc_costume_containers\\*, imf\\*, special\\*.

Usage (from the repository root):
  ../bin/pyt -t 60 tools/menu_unit_table.py [UNITLIST]    default work/generic/merged/tr8/pc-w/unitlist.txt
"""
import sys, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT = os.path.join(HERE, '..', 'work', 'generic', 'merged', 'tr8', 'pc-w', 'unitlist.txt')


def read_unitlist(path):
    with open(path, 'rb') as f:
        lines = [l for l in f.read().decode('latin1').split('\r\n') if l]
    assert int(lines[0]) == len(lines) - 1, 'count line does not match'
    return lines[1:]


def group_of(path):
    parts = path.lower().split('\\')
    unit = parts[-1]
    if parts[0] == 'levels':
        m = re.match(r'(l\d)_', unit)
        return ('Base game ' + m.group(1)) if m else None
    if parts[0] == 'dlc' and len(parts) >= 3:
        if parts[1] == 'dlc_level1': return 'DLC 1'
        if parts[1] == 'dlc_level2': return 'DLC 2'
        if re.match(r'dlc_level[3-6]$', parts[1]): return 'DLC other starts'
    return None


def main(argv):
    path = argv[0] if argv else DEFAULT
    units = read_unitlist(path)
    rows, skipped = [], []
    for p in units:
        g = group_of(p)
        if g is None: skipped.append(p); continue
        rows.append((g, p.split('\\')[-1], p))
    order = ['Base game l%d' % i for i in range(1, 8)] + ['DLC 1', 'DLC 2', 'DLC other starts']
    rows.sort(key=lambda r: (order.index(r[0]), units.index(r[2])))
    print('// generated by tools/menu_unit_table.py from %s (%d units, %d offered)' %
          (os.path.basename(path), len(units), len(rows)))
    for g, u, p in rows:
        print('    {"%s", "%s", "%s"},' % (g, u, p.replace('\\', '\\\\')))
    print('// not offered: %s' % ', '.join(skipped))
    counts = {}
    for g, _, _ in rows: counts[g] = counts.get(g, 0) + 1
    print('// per group: %s' % ', '.join('%s %d' % (g, counts[g]) for g in order if g in counts))


if __name__ == '__main__':
    main(sys.argv[1:])
